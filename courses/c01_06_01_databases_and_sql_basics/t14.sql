-- 14.2. 
1) Берёт данные из представления "Product Sales for 1997" (продажи отдельных товаров за 1997 год);
2) Группирует товары по категориям и рассчитывает общую сумму продаж для каждой категории;
3) Возвращает таблицу с двумя полями:
CategoryName - название категории товаров,
CategorySales - общая сумма продаж товаров этой категории за 1997 год.

-- 14.3. 
1) Берёт данные из таблиц "Customers", "Orders" и представления "Order Subtotals" (итоговая сумма по каждому заказу);
2) Отбирает заказы:
- дата отправки в 1997 году (01.01.1997 - 31.12.1997);
- итоговая сумма больше 2500;
3) Возвращает таблицу с четырьмя полями:
SaleAmount - итоговая сумма по заказу,
OrderID - номер заказа,
CompanyName - название компании-заказчика,
ShippedDate - дата отправки заказа.

-- 14.4. 
1) Берёт данные из таблицы "Products";
2) Рассчитывает среднюю цену всех товаров и отбирает товары, цена которых выше средней;
3) Возвращает таблицу с двумя полями:
ProductName - название товара,
UnitPrice - цена за единицу товара.

-- 14.5.
1) Берёт данные из таблицы "Orders" и представления "Order Subtotals" (итоговая сумма по каждому заказу);
2) Отбирает только отправленные заказы - поле ShippedDate заполнено, то есть не равно NULL;
3) Возвращает таблицу с тремя полями:
ShippedDate — дата отправки заказа,
OrderID — номер заказа,
Subtotal — итоговая сумма по заказу.


